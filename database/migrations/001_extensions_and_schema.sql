-- 001_extensions_and_schema.sql
-- Modelo de datos común SIG UAGRM 2026-2 (v1.0)
-- Compatible con PostgreSQL 18 + PostGIS 3.6 + pgRouting 4.0

CREATE EXTENSION IF NOT EXISTS postgis;
CREATE EXTENSION IF NOT EXISTS pgrouting;
CREATE EXTENSION IF NOT EXISTS unaccent;

-- Esquema separado para autenticación local JWT (sin alterar tablas del modelo común en public)
CREATE SCHEMA IF NOT EXISTS app_auth;

-- =====================================================================
-- 0. GRUPO
-- =====================================================================
CREATE TABLE IF NOT EXISTS public.grupo (
  id SMALLINT PRIMARY KEY CHECK (id BETWEEN 1 AND 22),
  codigo TEXT NOT NULL UNIQUE CHECK (codigo ~ '^[A-Z0-9-]+$'),
  tema TEXT NOT NULL,
  contacto TEXT,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- =====================================================================
-- 1. SEDE
-- =====================================================================
CREATE TABLE IF NOT EXISTS public.sede (
  id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo TEXT NOT NULL UNIQUE CHECK (codigo ~ '^[A-Z0-9-]+$'),
  nombre TEXT NOT NULL,
  tipo TEXT NOT NULL CHECK (tipo IN ('campus', 'sede_provincial', 'instalacion_externa')),
  municipio TEXT NOT NULL DEFAULT 'Santa Cruz de la Sierra',
  direccion TEXT,
  geom GEOMETRY(MULTIPOLYGON, 4326),
  area_m2 NUMERIC(12, 1),
  grupo_id SMALLINT NOT NULL REFERENCES public.grupo(id),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- =====================================================================
-- 2. UNIDAD (Organigrama sin geometría)
-- =====================================================================
CREATE TABLE IF NOT EXISTS public.unidad (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo TEXT NOT NULL UNIQUE CHECK (codigo ~ '^[A-Z0-9-]+$'),
  nombre TEXT NOT NULL,
  sigla TEXT,
  alias TEXT[] NOT NULL DEFAULT '{}',
  tipo TEXT NOT NULL CHECK (tipo IN (
    'autoridad', 'direccion', 'departamento', 'organo_especial',
    'gremio', 'postgrado', 'facultad', 'carrera', 'instituto', 'centro'
  )),
  responsable TEXT,
  cargo_responsable TEXT,
  descripcion TEXT,
  servicios TEXT[] NOT NULL DEFAULT '{}',
  correo TEXT,
  web TEXT,
  padre_id INTEGER REFERENCES public.unidad(id),
  grupo_id SMALLINT NOT NULL REFERENCES public.grupo(id),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT chk_unidad_padre_distinto CHECK (padre_id IS NULL OR padre_id <> id)
);

-- =====================================================================
-- 3. CATÁLOGOS DE LEYENDA
-- =====================================================================
CREATE TABLE IF NOT EXISTS public.tipo_area (
  id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo TEXT NOT NULL UNIQUE CHECK (codigo ~ '^[A-Z0-9_-]+$'),
  nombre TEXT NOT NULL,
  categoria TEXT NOT NULL,
  color TEXT NOT NULL CHECK (color ~ '^#[0-9A-Fa-f]{6}$'),
  icono TEXT NOT NULL,
  orden SMALLINT NOT NULL DEFAULT 0,
  descripcion TEXT,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.tipo_ambiente (
  id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo TEXT NOT NULL UNIQUE CHECK (codigo ~ '^[A-Z0-9_-]+$'),
  nombre TEXT NOT NULL,
  categoria TEXT NOT NULL,
  color TEXT NOT NULL CHECK (color ~ '^#[0-9A-Fa-f]{6}$'),
  icono TEXT NOT NULL,
  orden SMALLINT NOT NULL DEFAULT 0,
  descripcion TEXT,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.tipo_punto (
  id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo TEXT NOT NULL UNIQUE CHECK (codigo ~ '^[A-Z0-9_-]+$'),
  nombre TEXT NOT NULL,
  categoria TEXT NOT NULL,
  color TEXT NOT NULL CHECK (color ~ '^#[0-9A-Fa-f]{6}$'),
  icono TEXT NOT NULL,
  orden SMALLINT NOT NULL DEFAULT 0,
  descripcion TEXT,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.tipo_via (
  id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo TEXT NOT NULL UNIQUE CHECK (codigo ~ '^[A-Z0-9_-]+$'),
  nombre TEXT NOT NULL,
  categoria TEXT NOT NULL,
  color TEXT NOT NULL CHECK (color ~ '^#[0-9A-Fa-f]{6}$'),
  icono TEXT NOT NULL,
  orden SMALLINT NOT NULL DEFAULT 0,
  descripcion TEXT,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- =====================================================================
-- 4. EDIFICIO
-- =====================================================================
CREATE TABLE IF NOT EXISTS public.edificio (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo TEXT NOT NULL UNIQUE CHECK (codigo ~ '^[A-Z0-9-]+$'),
  nombre TEXT NOT NULL,
  alias TEXT[] NOT NULL DEFAULT '{}',
  uso TEXT NOT NULL CHECK (uso IN ('academico', 'administrativo', 'servicios', 'deportivo', 'mixto')),
  pisos SMALLINT NOT NULL DEFAULT 1 CHECK (pisos >= 1),
  ascensor BOOLEAN NOT NULL DEFAULT false,
  descripcion TEXT,
  geom GEOMETRY(MULTIPOLYGON, 4326),
  centro GEOMETRY(POINT, 4326),
  area_m2 NUMERIC(12, 1),
  sede_id SMALLINT NOT NULL REFERENCES public.sede(id),
  grupo_id SMALLINT NOT NULL REFERENCES public.grupo(id),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- =====================================================================
-- 5. AMBIENTE
-- =====================================================================
CREATE TABLE IF NOT EXISTS public.ambiente (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo TEXT NOT NULL UNIQUE CHECK (codigo ~ '^[A-Z0-9-]+$'),
  nombre TEXT NOT NULL,
  alias TEXT[] NOT NULL DEFAULT '{}',
  piso SMALLINT NOT NULL DEFAULT 0,
  referencia TEXT,
  encargado TEXT,
  telefono TEXT,
  horario TEXT,
  servicios TEXT[] NOT NULL DEFAULT '{}',
  descripcion TEXT,
  verificado_en DATE,
  geom GEOMETRY(POINT, 4326) NOT NULL,
  tipo_ambiente_id SMALLINT NOT NULL REFERENCES public.tipo_ambiente(id),
  unidad_id INTEGER REFERENCES public.unidad(id),
  edificio_id INTEGER REFERENCES public.edificio(id),
  sede_id SMALLINT REFERENCES public.sede(id),
  grupo_id SMALLINT NOT NULL REFERENCES public.grupo(id),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- =====================================================================
-- 6. PUNTO DE INTERÉS
-- =====================================================================
CREATE TABLE IF NOT EXISTS public.punto_interes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo TEXT NOT NULL UNIQUE CHECK (codigo ~ '^[A-Z0-9-]+$'),
  nombre TEXT,
  piso SMALLINT NOT NULL DEFAULT 0,
  accesible BOOLEAN NOT NULL DEFAULT false,
  nota TEXT,
  extintor_agente TEXT CHECK (extintor_agente IS NULL OR extintor_agente IN ('PQS', 'CO2', 'AGUA', 'ESPUMA', 'K')),
  extintor_kg NUMERIC(4, 1),
  extintor_vence DATE,
  verificado_en DATE,
  geom GEOMETRY(POINT, 4326) NOT NULL,
  tipo_punto_id SMALLINT NOT NULL REFERENCES public.tipo_punto(id),
  edificio_id INTEGER REFERENCES public.edificio(id),
  sede_id SMALLINT REFERENCES public.sede(id),
  grupo_id SMALLINT NOT NULL REFERENCES public.grupo(id),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- =====================================================================
-- 7. AREA
-- =====================================================================
CREATE TABLE IF NOT EXISTS public.area (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo TEXT NOT NULL UNIQUE CHECK (codigo ~ '^[A-Z0-9-]+$'),
  nombre TEXT,
  material TEXT CHECK (material IS NULL OR material IN ('cesped_natural', 'cesped_sintetico', 'cemento', 'tierra', 'pavimento', 'ripio')),
  capacidad SMALLINT,
  acceso TEXT NOT NULL DEFAULT 'publico' CHECK (acceso IN ('publico', 'restringido')),
  nota TEXT,
  verificado_en DATE,
  geom GEOMETRY(MULTIPOLYGON, 4326) NOT NULL,
  area_m2 NUMERIC(12, 1),
  tipo_area_id SMALLINT NOT NULL REFERENCES public.tipo_area(id),
  sede_id SMALLINT REFERENCES public.sede(id),
  unidad_id INTEGER REFERENCES public.unidad(id),
  grupo_id SMALLINT NOT NULL REFERENCES public.grupo(id),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- =====================================================================
-- 8. VIA Y VIA_NODO
-- =====================================================================
CREATE TABLE IF NOT EXISTS public.via_nodo (
  id INTEGER PRIMARY KEY,
  geom GEOMETRY(POINT, 4326) NOT NULL
);

CREATE TABLE IF NOT EXISTS public.via (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo TEXT NOT NULL UNIQUE CHECK (codigo ~ '^[A-Z0-9-]+$'),
  nombre TEXT,
  superficie TEXT CHECK (superficie IS NULL OR superficie IN ('asfalto', 'cemento', 'adoquin', 'tierra', 'ripio')),
  techado BOOLEAN NOT NULL DEFAULT false,
  accesible BOOLEAN NOT NULL DEFAULT true,
  verificado_en DATE,
  geom GEOMETRY(LINESTRING, 4326) NOT NULL,
  longitud_m NUMERIC(10, 1),
  tipo_via_id SMALLINT NOT NULL REFERENCES public.tipo_via(id),
  sede_id SMALLINT REFERENCES public.sede(id),
  origen INTEGER REFERENCES public.via_nodo(id),
  destino INTEGER REFERENCES public.via_nodo(id),
  grupo_id SMALLINT NOT NULL REFERENCES public.grupo(id),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- =====================================================================
-- 9. FOTO
-- =====================================================================
CREATE TABLE IF NOT EXISTS public.foto (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ruta TEXT NOT NULL UNIQUE,
  tipo TEXT NOT NULL CHECK (tipo IN ('fachada', 'puerta', 'interior', 'referencia')),
  principal BOOLEAN NOT NULL DEFAULT false,
  descripcion TEXT,
  tomada_en DATE,
  edificio_id INTEGER REFERENCES public.edificio(id) ON DELETE CASCADE,
  ambiente_id INTEGER REFERENCES public.ambiente(id) ON DELETE CASCADE,
  punto_interes_id INTEGER REFERENCES public.punto_interes(id) ON DELETE CASCADE,
  area_id INTEGER REFERENCES public.area(id) ON DELETE CASCADE,
  grupo_id SMALLINT NOT NULL REFERENCES public.grupo(id),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT chk_foto_un_dueno CHECK (num_nonnulls(edificio_id, ambiente_id, punto_interes_id, area_id) = 1)
);

-- =====================================================================
-- USUARIO LOCAL APP (Esquema auxiliar app_auth)
-- =====================================================================
CREATE TABLE IF NOT EXISTS app_auth.usuario_app (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  correo TEXT NOT NULL UNIQUE,
  nombre TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  rol TEXT NOT NULL DEFAULT 'editor' CHECK (rol IN ('admin', 'editor')),
  grupo_id SMALLINT NOT NULL DEFAULT 16 REFERENCES public.grupo(id),
  activo BOOLEAN NOT NULL DEFAULT true,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- =====================================================================
-- ÍNDICES ESPACIALES, GIN Y UNICIDAD PARCIAL
-- =====================================================================
CREATE INDEX IF NOT EXISTS idx_sede_geom ON public.sede USING GIST (geom);
CREATE INDEX IF NOT EXISTS idx_edificio_geom ON public.edificio USING GIST (geom);
CREATE INDEX IF NOT EXISTS idx_edificio_centro ON public.edificio USING GIST (centro);
CREATE INDEX IF NOT EXISTS idx_ambiente_geom ON public.ambiente USING GIST (geom);
CREATE INDEX IF NOT EXISTS idx_punto_interes_geom ON public.punto_interes USING GIST (geom);
CREATE INDEX IF NOT EXISTS idx_area_geom ON public.area USING GIST (geom);
CREATE INDEX IF NOT EXISTS idx_via_geom ON public.via USING GIST (geom);
CREATE INDEX IF NOT EXISTS idx_via_nodo_geom ON public.via_nodo USING GIST (geom);

CREATE INDEX IF NOT EXISTS idx_unidad_alias_gin ON public.unidad USING GIN (alias);
CREATE INDEX IF NOT EXISTS idx_unidad_servicios_gin ON public.unidad USING GIN (servicios);
CREATE INDEX IF NOT EXISTS idx_edificio_alias_gin ON public.edificio USING GIN (alias);
CREATE INDEX IF NOT EXISTS idx_ambiente_alias_gin ON public.ambiente USING GIN (alias);
CREATE INDEX IF NOT EXISTS idx_ambiente_servicios_gin ON public.ambiente USING GIN (servicios);

CREATE UNIQUE INDEX IF NOT EXISTS uq_foto_principal_edificio
  ON public.foto (edificio_id) WHERE principal = true AND edificio_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_foto_principal_ambiente
  ON public.foto (ambiente_id) WHERE principal = true AND ambiente_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_foto_principal_punto
  ON public.foto (punto_interes_id) WHERE principal = true AND punto_interes_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_foto_principal_area
  ON public.foto (area_id) WHERE principal = true AND area_id IS NOT NULL;
